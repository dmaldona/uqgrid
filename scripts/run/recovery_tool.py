#!/usr/bin/env python
"""
Recovery Tool for Failed Power Grid Simulation Scenarios.

This module provides utilities for analyzing, diagnosing, and recovering from
failed simulation runs in the power grid scenario generation pipeline. It helps
identify which scenarios failed, why they failed, and provides mechanisms to
retry only the failed scenarios without re-running the entire simulation.

Features
--------
- Analyze simulation logs to identify failed scenarios
- Group failures by fault location for pattern identification
- Verify data file integrity (detect corrupted or incomplete files)
- Generate retry scripts for failed scenarios only
- Export failed scenario lists for manual inspection

Usage
-----
Run interactively to analyze and recover from simulation failures::

    $ python recovery_tool.py

The tool will present a menu with recovery options after analyzing the
current simulation state.

Workflow
--------
1. Run your main simulation (generate_scenarios.py)
2. If failures occur, run this recovery tool
3. Analyze the failure patterns
4. Generate a retry script or export failed scenarios
5. Re-run only the failed scenarios with adjusted parameters

Required Files
--------------
- simulation_log.json : Log file from the main simulation containing
  scenario outcomes with 'diverged' and 'fault_location' fields.
- scenario_metadata.json : Original metadata file with scenario parameters
  (required for generating retry scripts).

Output Files
------------
- retry_metadata.json : Metadata for failed scenarios only
- retry_failed.py : Executable script to retry failed scenarios
- failed_scenarios.json : JSON export of failed scenario details

Environment Variables
---------------------
The script sets the following environment variables to prevent thread
contention when running with parallel processing:

- OMP_NUM_THREADS=1
- MKL_NUM_THREADS=1
- OPENBLAS_NUM_THREADS=1
- NUMEXPR_NUM_THREADS=1

Dependencies
------------
- scripts.run.generate_scenarios : Main simulation driver functions

Notes
-----
- The retry script uses conservative settings (single job, smaller batches)
  to improve success rate for problematic scenarios.
- Scenarios are considered "failed" if they diverged OR have no output file.
- Small files (<1KB) are flagged as potentially corrupted during integrity checks.

See Also
--------
- generate_scenarios.py : Main simulation script
- monitor.py : Real-time simulation monitoring

Example
-------
Typical recovery workflow::

    $ python recovery_tool.py
    
    Power Grid Simulation Recovery Tool
    ========================================
    
    === Simulation Status ===
    Total scenarios: 10000
    Succeeded: 9850 (98.5%)
    Failed: 150 (1.5%)
    ...
    
    === Recovery Options ===
    1. Create retry script for failed scenarios
    2. Export failed scenario list
    3. Exit
    
    Select option (1-3): 1
"""

