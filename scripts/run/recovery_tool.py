def analyze_simulation_log(log_file="simulation_log.json"):
    """
    Analyze the simulation log to identify and categorize failed scenarios.

    Reads the simulation log file and computes statistics on scenario outcomes,
    including success/failure rates and grouping failures by fault location
    to identify problematic buses.

    Parameters
    ----------
    log_file : str, default='simulation_log.json'
        Path to the JSON log file generated by the simulation. Expected format
        is a dictionary mapping scenario IDs to result dictionaries containing
        'diverged' (bool) and 'fault_location' (int/str) keys.

    Returns
    -------
    tuple of (dict, dict) or None
        - log : dict
            The complete simulation log dictionary.
        - failed_scenarios : dict
            Subset of log containing only failed scenarios (diverged=True
            or missing output file).
        
        Returns None if the log file doesn't exist.

    Examples
    --------
    >>> log, failed = analyze_simulation_log('my_simulation.json')
    >>> print(f"Failed scenarios: {len(failed)}")
    """
    # Verify log file exists
    if not os.path.exists(log_file):
        print(f"Error: {log_file} not found")
        return None

    # Load and parse the log file
    with open(log_file, 'r') as f:
        log = json.load(f)

    # Calculate summary statistics
    total = len(log)
    succeeded = sum(1 for s in log.values() if not s.get('diverged', True))
    failed = sum(1 for s in log.values() if s.get('diverged', True))
    missing_files = sum(1 for s in log.values() if s.get('file') is None)

    # Display status summary
    print(f"\n=== Simulation Status ===")
    print(f"Total scenarios: {total}")
    print(f"Succeeded: {succeeded} ({succeeded/total*100:.1f}%)")
    print(f"Failed: {failed} ({failed/total*100:.1f}%)")
    print(f"Missing files: {missing_files}")

    # Identify all failed scenarios (diverged OR missing output file)
    failed_scenarios = {
        sid: info for sid, info in log.items()
        if info.get('diverged', True) or info.get('file') is None
    }

    # Group failures by fault location for pattern analysis
    if failed_scenarios:
        print(f"\nFailed scenario IDs: {len(failed_scenarios)}")

        by_fault = {}
        for sid, info in failed_scenarios.items():
            floc = info.get('fault_location', 'unknown')
            if floc not in by_fault:
                by_fault[floc] = []
            by_fault[floc].append(sid)

        # Display failure distribution (helps identify problematic buses)
        print("\nFailed scenarios by fault location:")
        for floc in sorted(by_fault.keys()):
            if floc != 'unknown':
                print(f"  Fault location {floc}: {len(by_fault[floc])} failures")

    return log, failed_scenarios


def create_retry_script(failed_scenarios, metadata_file="scenario_metadata.json"):
    """
    Generate a retry script and metadata for failed scenarios only.

    Creates two files:
    1. A JSON file containing metadata for only the failed scenarios
    2. An executable Python script configured to retry those scenarios
       with more conservative simulation parameters.

    Parameters
    ----------
    failed_scenarios : dict
        Dictionary mapping scenario IDs to their failure information,
        as returned by analyze_simulation_log().
    metadata_file : str, default='scenario_metadata.json'
        Path to the original scenario metadata file containing parameters
        for all scenarios. Each failed scenario ID must exist in this file.

    Returns
    -------
    None
        Creates 'retry_metadata.json' and 'retry_failed.py' files.

    Notes
    -----
    The generated retry script uses conservative settings:
    - n_jobs=1 : Single process to avoid MPI/parallelization issues
    - batch_size=3 : Smaller batches for better error isolation
    - checkpoint_interval=10 : Frequent checkpoints to preserve progress

    Warnings
    --------
    The current implementation has an incomplete retry script generation.
    The retry_script variable is initialized but not fully populated.
    This is marked as a TODO for future development.
    """
    if not failed_scenarios:
        print("No failed scenarios to retry")
        return

    # Load the original metadata containing all scenario parameters
    with open(metadata_file, 'r') as f:
        all_metadata = json.load(f)

    # Extract metadata for only the failed scenarios
    retry_metadata = {sid: all_metadata[sid] for sid in failed_scenarios.keys()}

    # Save filtered metadata for retry
    retry_metadata_file = "retry_metadata.json"
    with open(retry_metadata_file, 'w') as f:
        json.dump(retry_metadata, f, indent=4)

    print(f"\nCreated {retry_metadata_file} with {len(retry_metadata)} scenarios to retry")

    # TODO: Complete the retry script generation
    # Currently only initializes the shebang line
    retry_script = "#!/usr/bin/env python"


