def main():
    """
    Main entry point for the interactive recovery tool.

    Provides a menu-driven interface for analyzing simulation status,
    checking data integrity, and initiating recovery operations.

    The workflow:
    1. Analyze simulation log to identify failures
    2. Check data file integrity
    3. Present recovery options to the user
    4. Execute selected recovery action

    Returns
    -------
    None
    """
    print("Power Grid Simulation Recovery Tool")
    print("=" * 40)

    # Step 1: Analyze current simulation status
    result = analyze_simulation_log()

    if result is None:
        return

    log, failed = result

    # Step 2: Check data file integrity
    check_data_integrity()

    # Step 3: Present recovery options if there are failures
    if failed:
        print("\n=== Recovery Options ===")
        print("1. Create retry script for failed scenarios")
        print("2. Export failed scenario list")
        print("3. Exit")

        choice = input("\nSelect option (1-3): ").strip()

        if choice == '1':
            create_retry_script(failed)
        elif choice == '2':
            # Export failed scenarios for external analysis or manual retry
            with open("failed_scenarios.json", 'w') as f:
                json.dump(failed, f, indent=4)
            print(f"Exported failed scenarios to failed_scenarios.json")
        # choice == '3' or invalid input: exit silently
    else:
        print("\nAll scenarios completed successfully!")


