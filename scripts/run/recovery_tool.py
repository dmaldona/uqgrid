def check_data_integrity():
    """
    Verify integrity of simulation output data files.

    Scans the simulation_data directory for .npz files and checks for
    potential issues such as missing or suspiciously small files that
    may indicate incomplete or corrupted writes.

    Returns
    -------
    None
        Prints diagnostic information to stdout.

    Warnings
    --------
    Files smaller than 1KB are flagged as potentially corrupted,
    as valid simulation output typically exceeds this size.

    Notes
    -----
    This function performs basic size-based validation only. For more
    thorough validation, consider loading each .npz file and verifying
    expected arrays are present and have correct shapes.
    """
    data_dir = Path("simulation_data")

    if not data_dir.exists():
        print("Warning: simulation_data directory not found")
        return

    # Find all scenario data files
    data_files = list(data_dir.glob("scenario_*.npz"))
    print(f"\nFound {len(data_files)} data files in {data_dir}")

    # Check for suspiciously small files (likely corrupted or incomplete)
    small_files = []
